                                                length:sizeof(kPrismAppleMusicGlyphPNGBytes)
                                          freeWhenDone:NO];
        image = [[NSImage alloc] initWithData:pngData];
    }
    return image;
}

/// Loads this plugin's own idle preset - see kPrismAppleMusicGlyphPNGBytes's own doc comment for
/// why this is a separate preset text/texture pair from ProjectMEngine.loadIdlePreset rather than
