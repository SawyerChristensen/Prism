/// Decodes kPrismScreenSaverLogoPNGBytes once and caches the NSImage - see that constant's own
/// doc comment.
static NSImage *PrismScreenSaverLogoImage(void) {
    static NSImage *image = nil;
    if (image == nil) {
        NSData *pngData = [NSData dataWithBytesNoCopy:(void *)kPrismScreenSaverLogoPNGBytes
                                                length:sizeof(kPrismScreenSaverLogoPNGBytes)
                                          freeWhenDone:NO];
        image = [[NSImage alloc] initWithData:pngData];
    }
    return image;
}

